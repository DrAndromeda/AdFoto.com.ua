#!/usr/bin/env python3
"""Generate public/.htaccess (301s from old .html URLs), public/llms.txt, public/llms-full.txt, public/robots.txt."""
import json, os, re, glob, html
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.environ.get('SITE_URL', 'https://adfoto.com.ua')
urlmap = json.load(open(os.path.join(ROOT, 'src/data-urlmap.json')))
pub = os.path.join(ROOT, 'public')

rules = ['# Generated by scripts/gen-seo.py - do not edit', 'RewriteEngine On', 'RewriteRule ^$ /ru/ [R=301,L]']
for old, new in sorted(urlmap.items()):
    if old == '/index.html': continue
    rules.append(f'RewriteRule ^{re.escape(old.lstrip("/"))}$ /ru{new} [R=301,L]')
rules += ['ErrorDocument 404 /404.html', '<IfModule mod_deflate.c>', 'AddOutputFilterByType DEFLATE text/html text/css application/javascript image/svg+xml', '</IfModule>',
          '<IfModule mod_expires.c>', 'ExpiresActive On', 'ExpiresByType image/jpeg "access plus 1 year"', 'ExpiresByType image/png "access plus 1 year"',
          'ExpiresByType image/webp "access plus 1 year"', 'ExpiresByType text/css "access plus 1 month"', 'ExpiresByType application/javascript "access plus 1 month"', '</IfModule>']
open(os.path.join(pub, '.htaccess'), 'w').write('\n'.join(rules) + '\n')

open(os.path.join(pub, 'robots.txt'), 'w').write(
    'User-agent: *\nAllow: /\n\n'
    + ''.join(f'User-agent: {b}\nAllow: /\n\n' for b in ['GPTBot', 'ChatGPT-User', 'OAI-SearchBot', 'ClaudeBot', 'Claude-User', 'PerplexityBot', 'Google-Extended', 'CCBot'])
    + f'Sitemap: {SITE}/sitemap-index.xml\n')

pages = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(ROOT, 'src/data/pages/ru/*.json')))]
groups = {}
for p in pages:
    if p['section'] in ('foto', 'reklama', 'branding', 'smm', 'web', 'blog'): groups.setdefault(p['section'], []).append(p)
names = {'foto': 'Photography', 'reklama': 'Advertising', 'branding': 'Branding & design', 'smm': 'SMM & marketing', 'web': 'Web & SEO', 'blog': 'Blog'}
lines = ['# AdFoto', '', '> Creative advertising agency in Kyiv (studio in Brovary): product, food and fashion photography, advertising, branding, SMM, websites and SEO. Site languages: Russian, Ukrainian, English.', '',
         '- Contacts: +380683534400, podely@adfoto.com.ua, Kyiv, Konstantinovskaya St. 1/2, office 48', '- Hours: daily 09:00-20:00', '- Prices: catalog and apparel photography from UAH 2000, food photography from UAH 2500; typical shoot 1-3 working days', '']
for g, ps in groups.items():
    lines.append(f'## {names[g]}')
    lines += [f'- [{p["h1"]}]({SITE}/ru{p["url"]}): {p["description"][:140]}' for p in ps]
    lines.append('')
open(os.path.join(pub, 'llms.txt'), 'w').write('\n'.join(lines))
full = []
for p in pages:
    if p['section'] in groups:
        txt = re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]+>', ' ', p['body']))).strip()
        full.append(f'# {p["h1"]}\nURL: {SITE}/ru{p["url"]}\n\n{txt}\n')
open(os.path.join(pub, 'llms-full.txt'), 'w').write('\n'.join(full))
print('htaccess rules', len(rules), 'llms pages', len(full))
